def physical_unit_aliases() -> dict[str, str]:
    result: dict[str, str] = {}
    for unit in DEFAULT_UNIT_ATTRIBUTES:
        aliases = set(UNIT_ALIASES.get(unit, ()))
        aliases.update(EXTRA_UNIT_ALIASES.get(unit, ()))
        aliases.add(unit)
        for alias in aliases:
            result[alias.casefold()] = unit
    return result


